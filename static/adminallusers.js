function downloadPDF() {
    const { jsPDF } = window.jspdf;

    // ✅ Landscape for wide table (IMPORTANT)
    const doc = new jsPDF({
        orientation: "landscape",
        unit: "pt",
        format: "a4"
    });

    // ✅ Title
    doc.setFontSize(16);
    doc.text("HostelHub - All Students", 40, 40);

    // ✅ Generate table
    doc.autoTable({
        html: '#userTable',
        startY: 60,
        theme: 'grid',

        styles: {
            fontSize: 9,          // mobile friendly
            cellPadding: 6,
            overflow: 'linebreak',
            halign: 'center',
            valign: 'middle'
        },

        headStyles: {
            fillColor: [123, 47, 247],
            textColor: 255,
            fontStyle: 'bold'
        },

        bodyStyles: {
            textColor: 20
        },

        alternateRowStyles: {
            fillColor: [245, 247, 255]
        },

        margin: { left: 20, right: 20 },

        didDrawPage: function () {
            doc.setFontSize(10);
            doc.text(
                "Generated by HostelHub",
                doc.internal.pageSize.width - 150,
                doc.internal.pageSize.height - 20
            );
        }
    });

    // ✅ MOBILE SAFE DOWNLOAD
    const fileName = "hostelhub_students.pdf";

    if (/Android|iPhone|iPad|iPod/i.test(navigator.userAgent)) {
        // Mobile: open PDF in new tab
        const pdfBlob = doc.output("bloburl");
        window.open(pdfBlob, "_blank");
    } else {
        // PC: direct download
        doc.save(fileName);
    }
}


function deleteUser(userId) {
    if (!confirm("Are you sure you want to delete this user?")) return;

    fetch(`/delete_user/${userId}`, { method: 'DELETE' })
        .then(res => {
            if (res.ok) {
                alert("User deleted successfully");
                location.reload();
            } else {
                alert("Failed to delete user");
            }
        })
        .catch(() => alert("Network error"));
}
